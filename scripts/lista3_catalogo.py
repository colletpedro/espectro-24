def lista():
    rows=[]
    for i,linha in enumerate(TEXTO.splitlines(),1):
        m=re.fullmatch(r'(.+) \((\d{4})\)',linha);assert m,linha
        titulo,ano=m[1],int(m[2]);ascii_=unicodedata.normalize('NFKD',titulo).encode('ascii','ignore').decode().lower()
        slug=SUGESTOES.get(titulo,re.sub('[^a-z0-9]+','-',ascii_).strip('-'))
        rows.append(dict(prioridade=i,titulo=titulo,ano=ano,sugestao=slug,requisitos=REQUISITOS.get((titulo,ano),{}),aliases=ALIASES.get(titulo,[])))
    assert len({(r['titulo'],r['ano']) for r in rows})==len(rows)
    return rows
